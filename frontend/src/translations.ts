const translationCache: Record<string, string> = {};

export function translateUI(key: string, lang: SupportedLanguage = 'en'): string {
  const table = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  return table[key] || UI_TRANSLATIONS.en[key] || key;
}

export async function translateTextOnline(text: string, targetLang: SupportedLanguage): Promise<string> {
  if (!text || targetLang === 'en') return text.replace(/[()]/g, '');

  const cacheKey = `${targetLang}:${text}`;
  if (translationCache[cacheKey]) {
    return translationCache[cacheKey];
  }

  try {
    const res = await fetch('http://localhost:3001/api/action/translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, targetLanguage: targetLang })
    });
    if (res.ok) {
      const data = await res.json();
      if (data.translated) {
        const clean = data.translated.replace(/[()]/g, '');
        translationCache[cacheKey] = clean;
        return clean;
      }
    }
  } catch {}

  return text.replace(/[()]/g, '');
}

