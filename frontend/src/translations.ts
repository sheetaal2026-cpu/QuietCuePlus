export function formatViewerState(state?: string, lang: SupportedLanguage = 'en'): string {
  if (!state) return '';
  const s = state.trim().toLowerCase();
  if (s.includes('watch') || s.includes('देख') || s.includes('lect') || s.includes('vien') || s.includes('wieder') || s.includes('視')) {
    return translateUI('watching', lang);
  }
  if (s.includes('pause') || s.includes('रोक') || s.includes('paus') || s.includes('停')) {
    return translateUI('paused', lang);
  }
  if (s.includes('break') || s.includes('विराम') || s.includes('pause') || s.includes('休')) {
    return translateUI('break', lang);
  }
  if (s.includes('summary') || s.includes('सारांश') || s.includes('résum') || s.includes('resumen') || s.includes('übersicht') || s.includes('ダイジェスト')) {
    return translateUI('summary', lang);
  }
  return state;
}

export function formatLastSyncEvent(eventText?: string, lang: SupportedLanguage = 'en'): string {
  if (!eventText) return '';
  if (eventText.includes('Connected & Ready') || eventText.includes('Ready') || eventText.includes('तैयार') || eventText.includes('prêt') || eventText.includes('bereit') || eventText.includes('待機')) {
    return translateUI('connectedAndReady', lang);
  }
  if (eventText.includes('Session Completed') || eventText.includes('Digest Ready')) {
    return translateUI('sessionCompletedDigestReady', lang);
  }
  if (eventText.includes('Break Triggered')) {
    return eventText.replace('Break Triggered', translateUI('break', lang));
  }
  if (eventText.includes('Live Event')) {
    return eventText.replace('Live Event', translateUI('triggerEvent', lang));
  }
  return eventText;
}
